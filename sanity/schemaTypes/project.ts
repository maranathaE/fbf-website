import { defineArrayMember, defineField, defineType } from 'sanity';
import { imageWithAlt, serviceOptions } from './fields';

export const project = defineType({
  name: 'project',
  title: 'Project',
  type: 'document',
  groups: [
    { name: 'basics', title: 'Basics', default: true },
    { name: 'story', title: 'Story' },
    { name: 'media', title: 'Media' },
    { name: 'credits', title: 'Credits' },
  ],
  fields: [
    defineField({ name: 'title', type: 'string', group: 'basics', validation: (r) => r.required() }),
    defineField({
      name: 'slug',
      type: 'slug',
      group: 'basics',
      description: 'The web address: fbf.studio/work/<slug>. Changing it breaks old links.',
      options: { source: 'title', maxLength: 96 },
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'clients',
      type: 'array',
      group: 'basics',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'client' }] })],
      validation: (r) => r.min(1),
    }),
    defineField({
      name: 'clientLabel',
      title: 'Client credit line',
      type: 'string',
      group: 'basics',
      description: 'How the client is credited, if different from the client names, e.g. "Gebeya Media Productions (for IFRC)".',
    }),
    defineField({
      name: 'services',
      type: 'array',
      group: 'basics',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: serviceOptions, layout: 'grid' },
      validation: (r) => r.min(1),
    }),
    defineField({ name: 'format', type: 'string', group: 'basics', description: 'e.g. Explainer, Lyric video, Event highlights' }),
    defineField({ name: 'year', type: 'number', group: 'basics' }),
    defineField({
      name: 'featured',
      type: 'boolean',
      group: 'basics',
      description: 'Show on the home page and in the reel playlist.',
      initialValue: false,
    }),
    defineField({ name: 'order', type: 'number', group: 'basics', description: 'Lower numbers come first.', hidden: true }),
    defineField({ name: 'description', type: 'text', rows: 5, group: 'story', validation: (r) => r.required() }),
    defineField({
      name: 'problem',
      type: 'text',
      rows: 3,
      group: 'story',
      description: 'Optional. What the client needed. Only shown when filled in.',
    }),
    defineField({ name: 'approach', type: 'text', rows: 3, group: 'story', description: 'Optional. How we solved it.' }),
    defineField({
      name: 'result',
      type: 'text',
      rows: 3,
      group: 'story',
      description: 'Optional. Real outcomes only (views, reach, audience, a client quote).',
    }),
    defineField({
      name: 'youtubeId',
      title: 'YouTube video ID',
      type: 'string',
      group: 'media',
      description: 'The part after "watch?v=" in the YouTube link.',
    }),
    defineField({
      name: 'loopMp4',
      title: 'Hover loop (MP4)',
      type: 'file',
      group: 'media',
      description: 'Optional 6–10 second muted loop, H.264, 960px wide, under 2 MB. Plays when hovering the project card.',
      options: { accept: 'video/mp4' },
    }),
    defineField({
      name: 'loopWebm',
      title: 'Hover loop (WebM)',
      type: 'file',
      group: 'media',
      options: { accept: 'video/webm' },
    }),
    imageWithAlt('cover', 'Cover image', { required: true, group: 'media' }),
    defineField({
      name: 'gallery',
      title: 'Frames',
      type: 'array',
      group: 'media',
      description: 'Stills in story order. They also power the onion-skin viewer on the project page.',
      of: [defineArrayMember({ type: 'image', options: { hotspot: true }, fields: [{ name: 'alt', title: 'Alt text', type: 'string' }] })],
      options: { layout: 'grid' },
    }),
    defineField({
      name: 'credits',
      type: 'array',
      group: 'credits',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'credit',
          fields: [
            defineField({ name: 'role', type: 'string', validation: (r) => r.required() }),
            defineField({ name: 'names', type: 'string', validation: (r) => r.required() }),
          ],
          preview: { select: { title: 'role', subtitle: 'names' } },
        }),
      ],
    }),
  ],
  orderings: [{ title: 'Manual order', name: 'order', by: [{ field: 'order', direction: 'asc' }] }],
  preview: { select: { title: 'title', subtitle: 'format', media: 'cover' } },
});
